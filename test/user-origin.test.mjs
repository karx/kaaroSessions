/**
 * test/user-origin.test.mjs → hooks/helpers/user-origin.mjs
 *
 * CC writes eight kinds of `user` row; only `human` and `command` are the
 * person typing. Fixtures mirror real row shapes (2026-11-10 audit of 60
 * sessions: 4297 tool_result-only, 174 human, 39 sidechain, 22 notification,
 * 20 command, 29 meta, 13 interrupt, 1 compact summary).
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { classifyClaudeUserOrigin } from '../hooks/helpers/user-origin.mjs';
import { USER_ORIGINS } from '../hooks/normalized-record.mjs';

const user = (content, flags = {}) => ({ type: 'user', message: { role: 'user', content }, ...flags });
const tr = (id = 't1') => ({ type: 'tool_result', tool_use_id: id, content: 'ok' });

const CASES = [
  ['human',           user('Check the latest on remote and the fork.')],
  ['human',           user([{ type: 'text', text: 'fix the landing copy' }])],
  ['human',           user([tr(), { type: 'text', text: 'also rename it' }]), 'hybrid: typed text beside a tool result'],
  ['tool_result',     user([tr('a'), tr('b')])],
  ['sidechain',       user('You are writing a design RFC for the repo', { isSidechain: true })],
  ['sidechain',       user([tr()], { isSidechain: true }), 'sidechain wins over tool_result'],
  ['compact_summary', user('This session is being continued from a previous conversation', { isCompactSummary: true })],
  ['interrupt',       user([{ type: 'text', text: '[Request interrupted by user]' }])],
  ['interrupt',       user('[Request interrupted by user for tool use]')],
  ['notification',    user('<task-notification> <task-id>a47b</task-id> <status>completed</status>')],
  ['meta',            user('Base directory for this skill: C:\\skills\\kaaro-design', { isMeta: true })],
  ['meta',            user('<local-command-caveat>The command below was run directly</local-command-caveat>', { isMeta: true })],
  ['meta',            user('<local-command-stdout>Set model to opus</local-command-stdout>'), 'command output is not typed'],
  ['meta',            user('<system-reminder>Your final report is delivered</system-reminder>'), 'reminder-only row'],
  ['meta',            user('Caveat: The messages below were generated by the user while running local commands.'), 'legacy caveat'],
  ['meta',            user('Base directory for this skill: C:\\skills\\agent-log <command-name>/agent-log</command-name>', { isMeta: true }),
                      'real row: isMeta skill body echoing command markup is not typed'],
  ['command',         user('<command-name>/voice</command-name> <command-message>voice</command-message>')],
  ['command',         user('<bash-input>git status</bash-input>'), '! shell typed by the human'],
  ['meta',            user('<bash-stdout>On branch master</bash-stdout><bash-stderr></bash-stderr>'), '! shell output'],
  ['command',         user('<command-message>review</command-message> <command-name>/review</command-name> <command-args>42</command-args>')],
];

for (const [want, rec, note] of CASES) {
  test(`classifyClaudeUserOrigin → ${want}${note ? ` (${note})` : ''}`, () => {
    assert.equal(classifyClaudeUserOrigin(rec), want);
  });
}

test('every classification is a member of the NR USER_ORIGINS enum', () => {
  for (const [, rec] of CASES) assert.ok(USER_ORIGINS.has(classifyClaudeUserOrigin(rec)));
});

test('empty / malformed rows default to human (never throw)', () => {
  assert.equal(classifyClaudeUserOrigin(user('')), 'human');
  assert.equal(classifyClaudeUserOrigin(user([])), 'human');
  assert.equal(classifyClaudeUserOrigin({ type: 'user' }), 'human');
});
